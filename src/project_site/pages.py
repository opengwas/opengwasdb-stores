"""Generate the site's pages from the collectors' JSON (#391, epic #385).

The site's data pages are written by a Python pre-render step from the five files
`pixi run site-data` writes, in the shapes `docs/spec/project-site.md` documents:
the overview (`index.qmd`), the Stores section (`stores.qmd` and one page per
registered Store), the Epics section (`epics.qmd` and one page per epic on the
board), the trends (`trends.qmd`) and the changelog (`changelog.qmd`).

Three rules hold on every page:

- **Every number traces to one collector field**, and a total is never shown
  when a part of it is unknown: it reads `unknown (k of n Stores report it)`,
  the rule `docs/spec/analysis-catalog.md` sets for the catalog's own summary.
- **A source that could not be read is a visible notice, never a crash.** Each
  page reads `available` before it reads anything else and says which source is
  missing, its error, and when it was collected.
- **No executable code cells**, so the render needs no kernel. A trend is a
  small inline SVG built here (no chart library, no new dependency), and a
  ticket graph is a Mermaid flowchart, which GitHub and the site both render.

`generate` writes into the tree Quarto is about to render, which is the docs
mirror `project_site.build` stages under `/data/opengwasdb/work/site`, never the
checkout: the pages are git-ignored there. `docs/_quarto.yml` runs it as the
project's `pre-render` hook, so `pixi run site` and `site-publish` both get the
pages from the data of the checkout being rendered. Quarto resolves the pages'
contents at render time, after pre-render, which is why a page it already knows
(`index.qmd`) may be replaced here and still render what this module wrote.
"""

from __future__ import annotations

import argparse
import html
import json
import sys
from pathlib import Path
from typing import Any, Mapping, Sequence

Document = Mapping[str, Any]

# The collectors, in the order `pixi run site-data` runs them, and the name each
# one's notice uses.
SOURCES = ("board", "catalog", "releases", "stores", "records")
TITLES = {
    "board": "Board data",
    "catalog": "Catalog data",
    "releases": "Releases data",
    "stores": "Stores data",
    "records": "Records data",
}

# The board's Workstream values, in the order the project reads them; a
# workstream the board gained since is listed after these, and an epic with none
# last.
WORKSTREAMS = (
    "Data architecture",
    "Build architecture",
    "Interface",
    "Store builds",
    "Tool integration",
    "Analyses",
    "Engineering",
)
NO_WORKSTREAM = "No workstream"

# Where a generated page says it came from, so a page rendered into a checkout by
# hand is not mistaken for an edited source file.
GENERATED = "<!-- generated by src/project_site/pages.py (#391): edit that module, not this page -->"

# The Release Bundle a Store page links to. The pages are built outside the
# checkout, so they cannot name the commit being rendered; `dev` is where the
# registry's bundles are, until the cutover moves them to `main`.
BUNDLES = "https://github.com/opengwas/opengwasdb-stores/tree/dev/stores"


# ---------------------------------------------------------------------------
# Reading the data
# ---------------------------------------------------------------------------


def load(data_dir: Path) -> dict[str, Document | None]:
    """The five collector files, as `pixi run site-data` wrote them.

    A file that was not written is `None`; one that cannot be read or parsed is
    an unavailable source with that error. Neither stops a page from rendering.
    """
    data_dir = Path(data_dir)
    documents: dict[str, Document | None] = {}
    for source in SOURCES:
        try:
            text = (data_dir / f"{source}.json").read_text(encoding="utf-8")
        except FileNotFoundError:
            documents[source] = None
            continue
        except OSError as error:
            documents[source] = _failed(source, f"{type(error).__name__}: {error}")
            continue
        try:
            document = json.loads(text)
        except ValueError as error:
            documents[source] = _failed(source, f"ValueError: {error}")
            continue
        if not isinstance(document, dict):
            documents[source] = _failed(source, "the file does not hold a JSON object")
            continue
        documents[source] = document
    return documents


def _failed(source: str, error: str) -> Document:
    """A source that could not be read at all, as the collectors write a failed one."""
    return {"source": source, "available": False, "collected_at": None, "error": error}


def available(documents: Mapping[str, Document | None], source: str) -> Document | None:
    """One source's file, or `None` when it was not collected or could not be read."""
    document = documents.get(source)
    if not isinstance(document, Mapping) or not document.get("available"):
        return None
    return document


# ---------------------------------------------------------------------------
# The visible notices and the text helpers every page shares
# ---------------------------------------------------------------------------


def notice(source: str, document: Document | None) -> str:
    """`Board data unavailable: <error>; collected <time>`, for a page's top."""
    title = TITLES[source]
    if document is None:
        return (
            f"> **{title} unavailable**: `{source}.json` was not written; collected never."
            " Run `pixi run site-data` and render again."
        )
    return f"> **{title} unavailable**: {_cell(document.get('error'))}; collected {_cell(document.get('collected_at'))}."


def notices(documents: Mapping[str, Document | None], sources: Sequence[str] = SOURCES) -> list[str]:
    """A notice and a blank line for every source of `sources` that is not available."""
    lines: list[str] = []
    for source in sources:
        document = documents.get(source)
        if isinstance(document, Mapping) and document.get("available"):
            continue
        lines += [notice(source, document), ""]
    return lines


def _cell(value: Any) -> str:
    """A value in a Markdown table cell: an unknown says so, pipes are escaped, lines folded."""
    if value is None:
        return "_not reported_"
    if isinstance(value, bool):
        return "yes" if value else "no"
    return " ".join(str(value).split()).replace("|", "\\|")


def _figure(value: Any) -> str:
    """A number with thousands separators, or the cell form of anything else."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return _cell(value)
    if isinstance(value, int):
        return f"{value:,}"
    return f"{value:g}"


def _link(text: Any, url: Any) -> str:
    """A Markdown link; the label is folded onto one line and its brackets escaped."""
    label = " ".join(str(text if text is not None else "").split()).replace("|", "\\|")
    label = label.replace("]", "\\]")
    return f"[{label}]({url})" if url else label


def epic_page_name(key: str) -> str:
    """The generated page's file name for an epic key (`repo#n`)."""
    return key.replace("#", "-")


def _epic_link(epic: Mapping[str, Any], prefix: str = "epics/") -> str:
    key = epic.get("key") or ""
    title = epic.get("title") or key
    return _link(title, f"{prefix}{epic_page_name(key)}.html")


def _workstream_order(groups: Mapping[str, Any]) -> list[str]:
    known = [name for name in WORKSTREAMS if name in groups]
    extra = sorted(name for name in groups if name not in WORKSTREAMS and name != NO_WORKSTREAM)
    return known + extra + ([NO_WORKSTREAM] if NO_WORKSTREAM in groups else [])


def sparkline(values: Sequence[float], *, label: str, width: int = 120, height: int = 22) -> str:
    """A small inline SVG trend: one circle per value, and a line through them.

    Written in Python without a chart library, so a page needs no dependency and
    no kernel. An empty series draws nothing.
    """
    numbers = [float(value) for value in values if value is not None]
    if not numbers:
        return ""
    left, right, top, bottom = 2.0, width - 2.0, 3.0, height - 3.0
    low, high = min(numbers), max(numbers)
    places = []
    for index, value in enumerate(numbers):
        x = left if len(numbers) == 1 else left + (right - left) * index / (len(numbers) - 1)
        y = (top + bottom) / 2 if high == low else bottom - (bottom - top) * (value - low) / (high - low)
        places.append((round(x, 1), round(y, 1)))
    points = " ".join(f"{x},{y}" for x, y in places)
    circles = "".join(f'<circle cx="{x}" cy="{y}" r="1.8"/>' for x, y in places)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-label="{html.escape(label)}">'
        f"<title>{html.escape(label)}</title>"
        f'<polyline fill="none" stroke="#2b6cb0" stroke-width="1.5" points="{points}"/>{circles}</svg>'
    )


def _trend(values: Sequence[Any], *, label: str) -> str:
    """A trend cell: the sparkline beside the first and last value it drew."""
    numbers = [value for value in values if isinstance(value, (int, float)) and not isinstance(value, bool)]
    if not numbers:
        return "_no version to compare_"
    drawn = sparkline(numbers, label=label)
    if len(numbers) == 1:
        return f"{drawn} one version"
    return f"{drawn} {_figure(numbers[0])} → {_figure(numbers[-1])} over {len(numbers)} versions"


# ---------------------------------------------------------------------------
# The yardstick's results, shared by the overview, the epic pages and the trends
# ---------------------------------------------------------------------------

# The timed measures the overview and the trends read, in the workload's order.
TIMED_MEASURES = ("open", "phewas_rsid", "phewas_alid", "phewas_position", "region", "analysis_full", "analysis_hm3")


def yardstick_results(documents: Mapping[str, Document | None]) -> list[Mapping[str, Any]]:
    """The valid yardstick results, oldest first; each is `{name, result}`."""
    records = available(documents, "records") or {}
    results = [
        entry
        for entry in (records.get("yardstick") or {}).get("results") or []
        if isinstance(entry, Mapping) and isinstance(entry.get("result"), Mapping)
    ]
    return sorted(results, key=lambda entry: str((entry["result"].get("started_utc") or entry.get("name") or "")))


def result_name(entry: Mapping[str, Any]) -> str:
    """A result's file name without its `.json`, which is how the site names one."""
    return str(entry.get("name") or "").removesuffix(".json")


def measured_stores(result: Mapping[str, Any]) -> list[Mapping[str, Any]]:
    return [store for store in result.get("stores") or [] if store.get("status") == "measured"]


def measure_value(record: Mapping[str, Any] | None) -> str:
    """One measure's value as a reader wants it, or why it is not there."""
    if record is None:
        return "_not reported_"
    status = record.get("status")
    if status == "unavailable":
        return f"unavailable ({_cell(record.get('error') or 'no error given')})"
    if status == "not_applicable":
        return "not applicable"
    if record.get("median_ms") is not None:
        return f"{_figure(record.get('median_ms'))} ms (p95 {_figure(record.get('p95_ms'))} ms)"
    if record.get("bytes") is not None:
        return f"{_figure(record.get('bytes'))} bytes ({_cell(record.get('source'))})"
    if record.get("peak_mb") is not None:
        return f"{_figure(record.get('peak_mb'))} MB peak (baseline {_figure(record.get('baseline_mb'))} MB)"
    return "_not reported_"


def measures_of(store: Mapping[str, Any]) -> Mapping[str, Any]:
    return store.get("measures") or {}


