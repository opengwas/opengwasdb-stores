def render_overview(documents: Mapping[str, Document | None]) -> str:
    """The home page: milestones, workstreams, headline numbers with trends, and each source's time."""
    lines = [GENERATED, ""]
    lines += notices(documents)
    lines += _milestones_section(documents)
    lines += _workstreams_section(documents)
    lines += _headline_section(documents)
    lines += _as_of_section(documents)
    return "\n".join(lines).rstrip() + "\n"


def _milestones_section(documents: Mapping[str, Document | None]) -> list[str]:
    """The open Milestones' progress, then the closed ones as one line.

    A closed Milestone is not progress to report: how many of its lines are met
    describes a plan nobody is working to any more, so it gets one short line and
    never a count, and a reader is not told a superseded milestone has "6 to go"
    (#391 fix 2).
    """
    lines = ["## Milestones", ""]
    board = available(documents, "board")
    if board is None:
        return lines + ["No milestone progress can be shown while the board data is unavailable.", ""]
    milestones = [item for item in board.get("milestones") or [] if isinstance(item, Mapping)]
    if not milestones:
        return lines + ["The board holds no Milestone.", ""]
    open_milestones = [item for item in milestones if not _is_closed(item)]
    closed = [item for item in milestones if _is_closed(item)]
    if not open_milestones:
        lines += ["No Milestone on the board is open.", ""]
    for item in open_milestones:
        checklist = item.get("lines") or []
        met = sum(1 for line in checklist if line.get("checked"))
        lines += [f"### {_link(item.get('title') or item.get('key'), item.get('url'))}", ""]
        if not checklist:
            lines.append("Its body holds no `- [ ]` line, so there is no progress to report.")
        else:
            lines.append(f"**{met} of {len(checklist)}** lines met, {len(checklist) - met} to go.")
            unmet = [line for line in checklist if not line.get("checked")]
            if unmet:
                lines += ["", "Not met yet:", ""] + [f"- {_cell(line.get('text'))}" for line in unmet]
        lines.append("")
    if closed:
        lines += ["Closed: " + "; ".join(_closed_milestone(item) for item in closed), ""]
    return lines


def _is_closed(item: Mapping[str, Any]) -> bool:
    """Whether the board reports the item's issue closed (`state` is the issue's, `OPEN` or `CLOSED`)."""
    return str(item.get("state") or "").upper() == "CLOSED"


def _closed_milestone(item: Mapping[str, Any]) -> str:
    """One closed Milestone as `Title (#n)`: its own text, and no count of what it did not finish."""
    number = str(item.get("key") or "").rsplit("#", 1)[-1]
    reference = _cell(f"#{number}") if number else _cell(None)
    return f"{_link(item.get('title') or item.get('key'), item.get('url'))} ({reference})"


def _workstreams_section(documents: Mapping[str, Document | None]) -> list[str]:
    lines = ["## Workstreams", ""]
    board = available(documents, "board")
    if board is None:
        return lines + ["No workstream can be shown while the board data is unavailable.", ""]
    active = [epic for epic in board.get("epics") or [] if (epic.get("status") or "") == "Active"]
    if not active:
        return lines + ["No epic on the board has Status **Active**.", ""]
    groups: dict[str, list[Mapping[str, Any]]] = {}
    for epic in active:
        groups.setdefault(epic.get("workstream") or NO_WORKSTREAM, []).append(epic)
    for name in _workstream_order(groups):
        lines += [f"### {escape(' '.join(name.split()))}", ""]
        for epic in sorted(groups[name], key=lambda item: str(item.get("key") or "")):
            tail = (
                f" Next: {_cell(epic.get('next'))}"
                if epic.get("next")
                else " No Next line on the board."
            )
            lines.append(f"- **{_epic_link(epic)}** — *{_cell(epic.get('status'))}*.{tail}")
        lines.append("")
    return lines


def _headline_section(documents: Mapping[str, Document | None]) -> list[str]:
    lines = ["## Headline numbers", ""]
    lines += _versions_section(documents)
    lines += _catalog_section(documents)
    lines += _yardstick_section(documents)
    return lines


def _versions_section(documents: Mapping[str, Document | None]) -> list[str]:
    lines = ["### Versions", ""]
    releases = available(documents, "releases")
    if releases is None:
        return lines + ["No version can be shown while the Releases data is unavailable.", ""]
    lines += ["| Repository | Latest tag | Tags |", "| --- | --- | --- |"]
    for repo in releases.get("repos") or []:
        tags = [tag for tag in repo.get("tags") or [] if tag.get("name")]
        latest = f"`{_cell(tags[0]['name'])}`" if tags else "untagged"
        lines.append(f"| {_cell(repo.get('repo'))} | {latest} | {len(tags)} |")
    lines += [
        "",
        "`gh api .../tags` lists the newest tag first, so that is the latest one. A tag is not a",
        "Release: the [changelog](changelog.html) lists Releases.",
        "",
    ]
    return lines


def _catalog_section(documents: Mapping[str, Document | None]) -> list[str]:
    lines = ["### The Analysis Catalog", ""]
    catalog = available(documents, "catalog")
    if catalog is None:
        return lines + ["No catalog figure can be shown while the Catalog data is unavailable.", ""]
    versions = [version for version in catalog.get("versions") or [] if isinstance(version, Mapping)]
    if not versions:
        return lines + ["No Analysis Catalog version has been built yet.", ""]
    # `current` names the version the catalog serves. When it names none, nothing
    # is current: the newest built version is not put in its place (#391 review).
    current = next((version for version in versions if version.get("current")), None)
    if current is None:
        lines += ["**No current version**: the catalog's `current` names none, so no version is called", "current here; the versions it holds are charted below.", ""]
    else:
        totals = current.get("totals") or {}
        built = (current.get("catalog_meta") or {}).get("built_at")
        lines += [
            f"The current version is `{_cell(current.get('version'))}`, built {_cell(built)}:"
            f" **{_figure(totals.get('analyses'))}** listed Analyses in"
            f" **{_figure(totals.get('stores'))}** Stores.",
            "",
        ]
    lines += ["| Figure | Newest collected | Movement |", "| --- | --- | --- |"]
    figures = (("Analyses", "analyses"), ("Stores", "stores"))
    for label, field in figures:
        series = [(version.get("totals") or {}).get(field) for version in versions]
        lines.append(f"| {label} | {_figure(series[-1])} | {_movement(series)} |")
    lines += ["", "The totals are `count(*)` on the listed Analyses, never a sum of the per-dimension counts, which overlap.", ""]
    for label, field in figures:
        series = [(version.get("totals") or {}).get(field) for version in versions]
        lines += _trend_block(
            series,
            label=f"{label} per catalog version",
            caption=f"{label}, per catalog version: {_movement(series)}.",
        )
    return lines


def _refused(records: Document | None, key: str = "invalid") -> list[tuple[str, list[str]]]:
    """The files a collector refused, with the errors it gave for each.

    A refused file is not an absent one: a page that says "none yet" over a
    directory of unreadable results reports the opposite of what happened
    (#391 review, item 3).
    """
    if records is None:
        return []
    refused = records.get(key) or {}
    return [(str(name), [str(error) for error in errors]) for name, errors in refused.items()]


def _yardstick_refusals(records: Document | None) -> list[tuple[str, list[str]]]:
    """The yardstick results the records collector refused, by file name and error."""
    if records is None:
        return []
    return _refused({"invalid": (records.get("yardstick") or {}).get("invalid")})


def _refused_notice(title: str, refused: Sequence[tuple[str, list[str]]]) -> list[str]:
    """A visible blockquote naming each refused file and why it was refused."""
    if not refused:
        return []
    lines = [f"> **{title}**: {len(refused)} file(s) the site could not use, so what they hold is missing", ">", ]
    lines += [f"> - `{_cell(name)}`: {_cell('; '.join(errors))}" for name, errors in refused]
    lines.append("")
    return lines


def _yardstick_section(documents: Mapping[str, Document | None]) -> list[str]:
    lines = ["### The yardstick", ""]
    records = available(documents, "records")
    results = yardstick_results(documents)
    refused = _yardstick_refusals(records)
    if records is None:
        return lines + ["No yardstick figure can be shown while the Records data is unavailable.", ""]
    if not results:
        lines += (
            ["**No yardstick results yet.** Each epic writes one under `docs/_yardstick/` when it finishes"
             " (`pixi run yardstick`, #390), and the trends appear here as they accumulate.", ""]
            if not refused
            else ["**No yardstick result could be read.**", ""]
        )
        return lines + _refused_notice("Yardstick results refused", refused)
    lines += _refused_notice("Yardstick results refused", refused)
    lines += ["| Result | Started | Engine | Duration | Measured Stores |", "| --- | --- | --- | --- | --- |"]
    for entry in results:
        result = entry["result"]
        stores = result.get("stores") or []
        measured = measured_stores(result)
        lines.append(
            "| "
            + " | ".join(
                [
                    _cell(result_name(entry)),
                    _cell(result.get("started_utc")),
                    _cell((result.get("opengwasdb") or {}).get("version")),
                    f"{_figure(result.get('duration_s'))} s",
                    f"{len(measured)} of {len(stores)}",
                ]
            )
            + " |"
        )
    lines += [
        "",
        f"The key figures of the latest result of each workload, `{_cell(result_name(results[-1]))}` among them,",
        "with their trend across that workload's results:",
        "",
    ]
    series_rows = _key_figure_series(results)
    if not series_rows:
        lines += ["No measure of the latest result was recorded.", ""]
    for figure in series_rows:
        caveat = (
            " A ringed point was measured in the Veeam backup window, so its timing is not comparable."
            if any(figure.warned) else ""
        )
        lines += _trend_block(
            figure.series,
            warned=figure.warned,
            label=f"{figure.measure} on {figure.store_id}, workload {figure.workload_id}",
            caption=(
                f"{_code(figure.measure)} on {figure.store_id} under workload {_code(figure.workload_id)}: "
                f"{_movement(figure.series, unit=figure.unit, span='results')}.{caveat}"
            ),
        )
    return lines


# The measures a headline trend is drawn for: what a reader compares between
# epics. The trends page carries the whole matrix.
KEY_MEASURES = (*TIMED_MEASURES, "peak_rss", "bytes_on_disk")


class KeyFigure(NamedTuple):
    """One trend line: what it measured, and the points, one per result of its workload."""

    workload_id: str
    store_id: str
    measure: str
    series: list[Any]
    warned: list[bool]
    unit: str


def workload_key(result: Mapping[str, Any]) -> str:
    """What a result measured: the sha256 that pins the workload file, or its id where the hash is missing.

    A result's `workload_sha256` is the workload file's digest, so two results
    with the same key measured the same benchmark; two with different keys are
    not a trend, whatever their Store and measure names say (#391 review, item 9).
    """
    return str(result.get("workload_sha256") or result.get("workload_id") or "?")


def workload_id(result: Mapping[str, Any]) -> str:
    return str(result.get("workload_id") or "?")


def workload_groups(results: Sequence[Mapping[str, Any]]) -> list[list[Mapping[str, Any]]]:
    """The results grouped by workload, each group in the order given (oldest first)."""
    groups: dict[str, list[Mapping[str, Any]]] = {}
    for entry in results:
        groups.setdefault(workload_key(entry["result"]), []).append(entry)
    return list(groups.values())


def _key_figure_series(results: Sequence[Mapping[str, Any]]) -> list[KeyFigure]:
    """One series per (workload, Store, measure) that workload's latest result measured.

    Each series holds a point per result of *its own* workload and nothing else,
    so a line never draws one workload's measurement beside another's -- the
    change a trend shows is in the code, not in the benchmark (#391 review, item 9).
    """
    figures: list[KeyFigure] = []
    for group in workload_groups(results):
        latest = group[-1]["result"]
        for store in measured_stores(latest):
            store_id = str(store.get("store_id") or "?")
            for measure in KEY_MEASURES:
                record = measures_of(store).get(measure)
                if record is None or record.get("status") == "not_applicable":
                    continue
                figures.append(
                    KeyFigure(
                        workload_id=workload_id(latest),
                        store_id=store_id,
                        measure=measure,
                        series=[_measure_number(_measure_of(entry["result"], store_id, measure)) for entry in group],
                        warned=[entry["result"].get("veeam_window") is True for entry in group],
                        unit=_measure_unit(measure),
                    )
                )
    return figures


def _measure_number(record: Mapping[str, Any] | None) -> Any:
    """The one number a measure's trend draws: its median, its bytes, or its peak memory."""
    if record is None or record.get("status") != "measured":
        return None
    for field in ("median_ms", "bytes", "peak_mb"):
        if isinstance(record.get(field), (int, float)) and not isinstance(record.get(field), bool):
            return record[field]
    return None


def _measure_unit(measure: str) -> str:
    if measure == "bytes_on_disk":
        return " bytes"
    if measure == "peak_rss":
        return " MB"
    return " ms"


def _as_of_section(documents: Mapping[str, Document | None]) -> list[str]:
    lines = ["## As of", "", "| Source | Collected | State |", "| --- | --- | --- |"]
    for source in SOURCES:
        document = documents.get(source)
        if document is None:
            lines.append(f"| {TITLES[source]} | never | not collected |")
        elif document.get("available"):
            lines.append(f"| {TITLES[source]} | {_cell(document.get('collected_at'))} | available |")
        else:
            lines.append(
                f"| {TITLES[source]} | {_cell(document.get('collected_at'))}"
                f" | unavailable: {_cell(document.get('error'))} |"
            )
    lines.append("")
    return lines


