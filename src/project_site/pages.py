def notice(source: str, document: Document | None) -> str:
    """`Board data unavailable: <error>; collected <time>`, for a page's top."""
    title = TITLES[source]
    if document is None:
        return (
            f"> **{title} unavailable**: `{source}.json` was not written; collected never."
            " Run `pixi run site-data` and render again."
        )
    return f"> **{title} unavailable**: {_cell(document.get('error'))}; collected {_cell(document.get('collected_at'))}."


def notices(documents: Mapping[str, Document | None], sources: Sequence[str] = SOURCES) -> list[str]:
    """A notice and a blank line for every source of `sources` that is not available."""
    lines: list[str] = []
    for source in sources:
        document = documents.get(source)
        if isinstance(document, Mapping) and document.get("available"):
            continue
        lines += [notice(source, document), ""]
    return lines


# Every value a page shows is a collector's field, so it is data: Markdown and
# HTML it happens to hold are shown as written, never obeyed. A title of
# `<b>x</b> *y* [z](w) | q` must read as that text, not bolden a page, link a
# word and cut a table cell in two -- a wrong answer that looks like a right one.
ESCAPES = {
    "\\": "\\\\",
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    "*": "\\*",
    "_": "\\_",
    "`": "\\`",
    "[": "\\[",
    "]": "\\]",
    "|": "\\|",
}

# What starts a block in Markdown, so a paragraph of a fact is never read as one.
BLOCK_START = re.compile(r"^([#\-+]|\d+[.)])")


def escape(text: str) -> str:
    """`text` as literal Markdown: no tag, emphasis, code span, link or table cell of its own."""
    return "".join(ESCAPES.get(character, character) for character in text)


def _cell(value: Any) -> str:
    """A value in a Markdown table cell: an unknown says so, and the rest is literal."""
    if value is None:
        return "_not reported_"
    if isinstance(value, bool):
        return "yes" if value else "no"
    return escape(" ".join(str(value).split()))


def _figure(value: Any) -> str:
    """A number with thousands separators, or the cell form of anything else."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return _cell(value)
    if isinstance(value, int):
        return f"{value:,}"
    return f"{value:g}"


#: Characters Markdown still reads inside an inline `<code>`: pandoc parses the text
#: between the tags as Markdown, so a fact's own `*`, `_`, `[`, `~`, `$`, `^`, `\`
#: or backtick would become emphasis, a link, a subscript, math, a superscript,
#: an escape or a code span of its own. Their numeric entities render as the
#: character and are read as neither Markdown nor a table cell's `|`.
_CODE_ENTITIES = str.maketrans({
    "\\": "&#92;", "`": "&#96;", "*": "&#42;", "_": "&#95;", "[": "&#91;",
    "]": "&#93;", "^": "&#94;", "$": "&#36;", "~": "&#126;", "|": "&#124;",
})
#: What a Markdown code span cannot hold: a backtick closes it, and a pipe cuts the
#: table cell it sits in. A version tag is free text -- `v`<b>x</b>` is a legal one.
_CODE_RISKY = re.compile(r"[`|]")


def _code(value: Any) -> str:
    """A fact in a code span, rendered literally whatever it holds.

    A plain code span is used when the value cannot close its fence or cut its
    table cell, so the common value stays readable in the Markdown source. A
    value that can does not fit a Markdown code span at all, so it is written as
    HTML: `<code>` with the text escaped as HTML and its Markdown-active
    characters as entities, which no reader turns back into markup (#391
    review, item 2).
    """
    text = " ".join(str(value).split())
    if not _CODE_RISKY.search(text):
        return f"`{text}`"
    return "<code>" + html.escape(text, quote=False).translate(_CODE_ENTITIES) + "</code>"


def _link(text: Any, url: Any) -> str:
    """A Markdown link whose label is a fact: escaped, and folded onto one line."""
    label = escape(" ".join(str(text if text is not None else "").split()))
    if not url:
        return label
    destination = str(url)
    if any(character in destination for character in " ()<>"):
        destination = f"<{destination}>"
    return f"[{label}]({destination})"


def _prose(text: Any) -> str:
    """Free text as paragraphs of literal text: escaped, one line each, never a block start."""
    paragraphs = [" ".join(line.split()) for line in re.split(r"\n\s*\n", str(text).strip())]
    rendered = []
    for paragraph in paragraphs:
        if not paragraph:
            continue
        literal = escape(paragraph)
        if BLOCK_START.match(literal):
            literal = "\\" + literal
        rendered.append(literal)
    return "\n\n".join(rendered)


def _title_block(title: Any) -> str:
    """The front matter a generated page starts with: its title is a fact, so it is escaped."""
    return f"---\ntitle: {json.dumps(escape(' '.join(str(title).split())), ensure_ascii=False)}\n---\n"


def epic_page_name(key: str) -> str:
    """The generated page's file name for an epic key (`repo#n`)."""
    return key.replace("#", "-")


# Where the per-epic and per-Store pages live, and the prefix a root page needs to
# reach one: a link is only a link if it resolves to the page that was written.
EPIC_PAGES = "epics"
STORE_PAGES = "stores"


def store_page_name(store_id: str) -> str:
    """The generated page's file name inside the Stores directory for a Store id."""
    return f"{STORE_PAGES}/{store_id}"


def _epic_link(epic: Mapping[str, Any], prefix: str = "epics/") -> str:
    key = epic.get("key") or ""
    title = epic.get("title") or key
    return _link(title, f"{prefix}{epic_page_name(key)}.html")


def _workstream_order(groups: Mapping[str, Any]) -> list[str]:
    known = [name for name in WORKSTREAMS if name in groups]
    extra = sorted(name for name in groups if name not in WORKSTREAMS and name != NO_WORKSTREAM)
    return known + extra + ([NO_WORKSTREAM] if NO_WORKSTREAM in groups else [])


def sparkline(
    values: Sequence[float], *, label: str, width: int = 120, height: int = 22, warned: Sequence[bool] | None = None
) -> str:
    """A small inline SVG trend: one circle per value, and a line through them.

    Written in Python without a chart library, so a page needs no dependency and
    no kernel. An empty series draws nothing. A value `warned` names is ringed as
    well as dotted, so a point that was not measured under comparable conditions
    -- the yardstick's Veeam backup window -- is visible in the figure itself
    (#391 review, item 9).
    """
    drawn = [
        (index, float(value))
        for index, value in enumerate(values)
        if isinstance(value, (int, float)) and not isinstance(value, bool)
    ]
    numbers = [value for _, value in drawn]
    if not numbers:
        return ""
    flags = list(warned) if warned is not None else []
    left, right, top, bottom = 2.0, width - 2.0, 3.0, height - 3.0
    low, high = min(numbers), max(numbers)
    places = []
    for index, value in enumerate(numbers):
        x = left if len(numbers) == 1 else left + (right - left) * index / (len(numbers) - 1)
        y = (top + bottom) / 2 if high == low else bottom - (bottom - top) * (value - low) / (high - low)
        places.append((round(x, 1), round(y, 1)))
    points = " ".join(f"{x},{y}" for x, y in places)
    circles = ""
    for (index, _), (x, y) in zip(drawn, places):
        marked = index < len(flags) and flags[index]
        fill = ' fill="#b7791f"' if marked else ""
        circles += f'<circle cx="{x}" cy="{y}" r="1.8"{fill}/>'
        if marked:
            circles += f'<circle cx="{x}" cy="{y}" r="3.4" fill="none" stroke="#b7791f" stroke-width="1"/>'
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-label="{html.escape(label)}">'
        f"<title>{html.escape(label)}</title>"
        f'<polyline fill="none" stroke="#2b6cb0" stroke-width="1.5" points="{points}"/>{circles}</svg>'
    )


def _numbers(values: Sequence[Any]) -> list[float]:
    """The values a trend can draw: a number, never a bool, never an unknown."""
    return [float(value) for value in values if isinstance(value, (int, float)) and not isinstance(value, bool)]


def _movement(values: Sequence[Any], *, unit: str = "", span: str = "versions") -> str:
    """The first and last of a series in words: `19,250 → 31,940 over 3 versions`."""
    drawn = [value for value in values if isinstance(value, (int, float)) and not isinstance(value, bool)]
    if not drawn:
        return "not charted"
    if len(drawn) == 1:
        return f"{_figure(drawn[0])}{unit} in the one {span[:-1]}"
    return f"{_figure(drawn[0])}{unit} → {_figure(drawn[-1])}{unit} over {len(drawn)} {span}"


def _trend_block(
    values: Sequence[Any], *, label: str, caption: str, warned: Sequence[bool] | None = None
) -> list[str]:
    """A trend line as a raw HTML block, which Pandoc passes through untouched.

    An SVG written inline in a Markdown table cell loses its children in the
    render (a `<title>` child makes Pandoc drop them), so every chart is a block
    of its own, under the figure it charts (#391 review, item 6).
    """
    if not _numbers(values):
        return []
    return [caption, "", "```{=html}", sparkline(values, label=label, warned=warned), "```", ""]


