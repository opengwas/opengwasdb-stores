def test_partial_store_cannot_masquerade(fixture: Fixture) -> None:
    """A partial Store with no completion record is rebuilt, not trusted.

    This is what an interrupted build leaves behind: the completed phases keep
    their records, the build and everything after it have none, and the Store
    path holds whatever the killed process had written. The rerun must descend
    into the missing phases and replace the partial Store.
    """
    resolve_hash = sha256(fixture.completion("resolve_analysis_metadata"))

    for phase in ("build_observed_store", "regenerate_observed_overview", "validate_observed_release"):
        fixture.completion(phase).unlink()
    (fixture.store_dir / "manifest.json").unlink()
    (fixture.store_dir / "PARTIAL").write_text("interrupted build\n", encoding="utf-8")

    result = snakemake(fixture)
    assert_success(result, "partial-store rerun")
    check(not (fixture.store_dir / "PARTIAL").exists(), "the partial Store survived the rerun")
    check((fixture.store_dir / "manifest.json").is_file(), "the rerun did not rebuild the Store envelope")
    check(store_analysis_ids(fixture) == list(FIXTURE_ANALYSES), "the rebuilt Store carries the wrong Analyses")
    check(fixture.validation()["checks"].get("store") == "passed", "the rebuilt Store did not validate")
    check(sha256(fixture.completion("resolve_analysis_metadata")) == resolve_hash,
          "the rerun re-ran the already-complete resolve phase")
    check(not fixture.store_dir.with_name(fixture.store_dir.name + ".partial").exists(),
          "the build left its .partial sibling behind")


def test_edits_invalidate_and_flow_through(fixture: Fixture) -> None:
    """Editing build.yaml, analyses.tsv, or a source file invalidates the affected phases.

    Each edit is checked with a dry run -- the DAG Snakemake would execute --
    and then one real run proves all three edits actually reach the Store.
    """
    before_build = sha256(fixture.completion("build_observed_store"))

    fixture.build_yaml.write_text(
        fixture.build_yaml.read_text(encoding="utf-8").replace("n-workers: 1", "n-workers: 2"),
        encoding="utf-8",
    )
    check("build_observed_store" in planned_rules(snakemake(fixture, dry_run=True)),
          "editing build.yaml did not invalidate the build phase")

    rewrite_analyses(fixture, lambda row: row.update(
        {"analysis_label": "Edited body mass index"} if row["analysis_id"] == BMI else {}
    ))
    check("resolve_analysis_metadata" in planned_rules(snakemake(fixture, dry_run=True)),
          "editing analyses.tsv did not invalidate the resolve phase")

    edited_source = fixture.release_dir / "source" / "finngen_R13_BMI_FIXTURE.gz"
    append_variant(edited_source, ["8", "9000000", "A", "C", "0.04", "0.02", "0.37", "rs9"])
    new_checksum = sha256(edited_source)
    rewrite_analyses(fixture, lambda row: row.update(
        {"checksum": new_checksum} if row["analysis_id"] == BMI else {}
    ))
    check("build_observed_store" in planned_rules(snakemake(fixture, dry_run=True)),
          "editing a source file did not invalidate the build phase")

    result = snakemake(fixture)
    assert_success(result, "edited inputs rerun")
    check(sha256(fixture.completion("build_observed_store")) != before_build,
          "the edited inputs did not re-run the build")
    labels = {row["analysis_id"]: row["analysis_label"] for row in read_tsv(fixture.store_dir / "analyses.tsv")}
    check(labels[BMI] == "Edited body mass index", "the edited label did not reach the Store")
    report = read_tsv(fixture.sidecar("build-report.tsv"))[0]
    check(int(report["n_variants"]) == FIXTURE_VARIANTS + 1, "the new source variant did not reach the Store")
    command = fixture.record("build_observed_store")["command"]
    check("--n-workers" in command and "2" in command, "the edited build argument did not reach the CLI")
    check(fixture.validation()["checks"].get("store") == "passed", "the release did not validate after the edits")


