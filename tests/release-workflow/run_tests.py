def test_file_name_source_column(temp_root: Path) -> None:
    """analyses.tsv may name its source column `file_name` instead of `source_file`.

    `resources/lib/release_plan.py` and `workflow/model.py` both accept either
    name. The resolve phase must resolve `file_name` the same way, or the shared
    builder manifest points at the source directory rather than each file.
    """
    fixture = prepare(temp_root, "file-name-column")
    lines = fixture.analyses.read_text(encoding="utf-8").splitlines()
    header = lines[0].split("\t")
    header[header.index("source_file")] = "file_name"
    lines[0] = "\t".join(header)
    fixture.analyses.write_text("\n".join(lines) + "\n", encoding="utf-8")

    result = snakemake(fixture)
    assert_success(result, "file_name source column build")
    check(store_analysis_ids(fixture) == list(FIXTURE_ANALYSES),
          "the file_name-column release built the wrong Analyses")
    # The resolved table persists the absolute usable path under the canonical
    # `source_file` name even though the fixed input spelled it `file_name`.
    resolved = read_tsv(fixture.work_dir / "analyses.resolved.tsv")
    check(resolved and all("source_file" in row for row in resolved),
          "the resolved table dropped source_file for a file_name-column release")
    for row in resolved:
        source = Path(row["source_file"])
        check(source.is_absolute(), f"resolved source_file {row['source_file']!r} is not absolute")
        check(source.is_file(), f"resolved source_file {row['source_file']!r} is not a source file")
    manifest = read_tsv(fixture.work_dir / "builder-manifest.tsv")
    check(len(manifest) == len(FIXTURE_ANALYSES), "builder manifest row count mismatch")
    for row in manifest:
        file_path = Path(row["file_path"])
        check(file_path.is_absolute(), f"builder manifest file_path {row['file_path']!r} is not absolute")
        check(file_path.is_file(), f"builder manifest file_path {row['file_path']!r} is not a source file")


