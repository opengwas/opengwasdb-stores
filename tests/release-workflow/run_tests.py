def test_scratch_build(temp_root: Path) -> Fixture:
    """One command builds a genuine Store with real resolved metadata."""
    fixture = prepare(temp_root, "scratch")
    committed_before = sha256(fixture.analyses)
    result = snakemake(fixture)
    assert_success(result, "scratch build")

    check(fixture.store_dir.is_dir(), "the fixture Store was not built")
    manifest = json.loads((fixture.store_dir / "manifest.json").read_text(encoding="utf-8"))
    check(manifest["store_id"] == "finngen-r13", f"unexpected store_id {manifest['store_id']!r}")
    check(manifest["release_id"] == "r13-fixture", f"unexpected release_id {manifest['release_id']!r}")
    check(manifest["format_version"] == "1.0", f"unexpected store format {manifest['format_version']!r}")
    check(store_analysis_ids(fixture) == list(FIXTURE_ANALYSES), "built Store carries the wrong Analyses")
    check((fixture.store_dir / "data.zarr").is_dir(), "built Store has no data.zarr")

    # AC1: the committed analyses.tsv is read-only to the workflow.
    check(sha256(fixture.analyses) == committed_before,
          "the run mutated the committed analyses.tsv (issue #99 AC1)")

    overview = (fixture.store_dir / "overview.html").read_text(encoding="utf-8")
    check("<html>" in overview, "overview.html is not HTML")
    for analysis_id in FIXTURE_ANALYSES:
        check(analysis_id in overview, f"overview.html omits {analysis_id}")

    # AC2/AC3: derived ancestry and effect-scale metadata reach the resolved
    # file and the built Store.
    resolved = {row["analysis_id"]: row for row in read_tsv(fixture.work_dir / "analyses.resolved.tsv")}
    check(resolved[BMI]["original_sd_method"] == "estimated_from_source_maf",
          "the derived phenotype-SD method is not in the resolved file")
    check(resolved[BMI]["original_sd"], "the derived phenotype SD is not in the resolved file")
    check("ancestry_prop_EUR" in resolved[HEIGHT], "the ancestry proportions are not in the resolved file")

    store = fixture.store_analyses()
    for analysis_id in FIXTURE_ANALYSES:
        expected_scale = "log_or" if analysis_id == RX_STATIN else "sd"
        check(store[analysis_id]["assigned_ancestry"] == "EUR",
              f"{analysis_id} did not reach the Store with an assigned ancestry")
        check(store[analysis_id]["ancestry_assignment_method"] == "af_assigned",
              f"{analysis_id} did not reach the Store with af_assigned")
        check("ancestry_prop_EUR" in store[analysis_id],
              f"{analysis_id} did not reach the Store with ancestry proportions")
        check(store[analysis_id]["stored_effect_scale"] == expected_scale,
              f"{analysis_id} reached the Store with the wrong effect scale")
    check(store[BMI]["original_sd_method"] == "estimated_from_source_maf",
          "the derived phenotype-SD method did not reach the Store")
    check(store[BMI]["original_sd"], "the derived phenotype SD did not reach the Store")
    check(store[HEIGHT]["original_sd_method"] == "declared_standardised",
          "the declared-standardised method was not preserved")

    # AC4: the failed effect-scale check is recorded, and does not fail the run.
    validation = fixture.validation()
    check(validation["status"] == "failed", f"validation.yaml status is {validation['status']!r}")
    check(validation["checks"].get("store") == "passed", "the CLI store check did not pass")
    check(validation["checks"].get("files") == "passed", "the build file check did not pass")
    check(validation["checks"].get("schema") == "passed", "the schema check did not pass")
    check(validation["checks"].get("ancestry") == "passed", "the ancestry check did not pass")
    check(validation["checks"].get("effect_scale") == "failed", "the effect-scale failure was not recorded")
    check(validation["checks"].get("sd_estimation") == "failed", "the SD-estimation failure was not recorded")
    check(any(HEIGHT in warning and "effect-scale" in warning for warning in validation["warnings"]),
          "validation.yaml warnings do not name the failed effect-scale Analysis")

    # AC4: the release lands as `built`, not `validated`.
    check(fixture.release_status() == "built",
          f"a failed effect-scale check should land the release as built, got {fixture.release_status()!r}")

    # AC6: the resolution report names every Analysis whose metadata was derived.
    resolution = read_tsv(fixture.sidecar("metadata-resolution.tsv"))
    check([row["analysis_id"] for row in resolution] == list(FIXTURE_ANALYSES),
          "metadata-resolution.tsv does not cover every Analysis")
    derived = {row["analysis_id"] for row in resolution if row["derived_fields"]}
    check(derived == set(FIXTURE_ANALYSES), "the resolution report does not name every derived Analysis")
    report = {row["analysis_id"]: row for row in resolution}
    check("original_sd" in report[BMI]["derived_fields"], "BMI's derived SD is not reported")
    check(report[HEIGHT]["effect_scale_status"] == "failed", "HEIGHT's failed check is not reported")
    check(report[RX_STATIN]["effect_scale_status"] == "skipped", "the binary Analysis should be skipped")

    for phase in PHASES:
        check(fixture.completion(phase).is_file(), f"no completion record for {phase}")

    report = read_tsv(fixture.sidecar("build-report.tsv"))[0]
    check(int(report["n_analyses"]) == len(FIXTURE_ANALYSES), "build report n_analyses mismatch")
    check(int(report["n_variants"]) == FIXTURE_VARIANTS, "build report n_variants mismatch")
    check(report["status"] == "passed", "build report is not passed")
    check("/store.opengwasdb.partial " in report["command"] + " ", "build did not build into a .partial sibling")

