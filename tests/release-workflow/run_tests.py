    # AFR; the EUR build keeps the former and does not build the latter.
    catalogue = {row["trait_id"]: row for row in read_tsv(fixture.analysis_catalogue)}
    check([row["trait_id"] for row in read_tsv(fixture.analysis_catalogue)] == list(CATALOGUE_ANALYSES),
          "the Analysis Catalogue does not cover every Analysis in order")
