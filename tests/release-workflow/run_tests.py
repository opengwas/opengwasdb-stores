def interrupt_completion(fixture: Fixture) -> None:
    """Run the completion phase and kill it once opengwasdb has checkpointed.

    This leaves exactly what an interrupted completion leaves: a checkpoint
    directory and the phase's own resume marker, but no child Store at its own
    path and no completion record. The whole process group is killed so the
    spawned `opengwasdb complete-dense` dies with the phase runner rather than
    finishing in the background.
    """
    child = child_of(fixture)
    partial = child.store_dir.with_name(child.store_dir.name + ".partial")
    build_params = partial.parent / f".{partial.name}.checkpoint" / "build_params.json"
    process = subprocess.Popen(
        [sys.executable, str(PHASE_RUNNER), "--phase", "complete_store",
         "--config", str(fixture.build_yaml), "--repo-root", str(REPO_ROOT)],
        cwd=REPO_ROOT, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
        start_new_session=True,
    )
    killed = False
    try:
        deadline = time.time() + 60
        while time.time() < deadline:
            if build_params.is_file():
                try:
                    json.loads(build_params.read_text(encoding="utf-8"))
                except ValueError:
                    time.sleep(0.005)
                    continue
                os.killpg(os.getpgid(process.pid), signal.SIGKILL)
                killed = True
                break
            if process.poll() is not None:
                break
            time.sleep(0.005)
    finally:
        if not killed and process.poll() is None:
            os.killpg(os.getpgid(process.pid), signal.SIGKILL)
    output = process.communicate()[0]
    check(killed, f"the completion finished before it could be interrupted:\n{output[-2000:]}")


