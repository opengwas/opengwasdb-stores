    release_dir = scenario / "release"
    shutil.copytree(FIXTURE, release_dir)
    artifacts = scenario / "artifacts"
    build_yaml = release_dir / "build.yaml"
    text = build_yaml.read_text(encoding="utf-8")
    assert "artifact_root: .release-work" in text, "fixture build.yaml no longer declares the repo-local root"
