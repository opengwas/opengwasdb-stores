    check((fixture.store_dir / "manifest.json").is_file(), "the rerun did not rebuild the Store envelope")
    check(store_analysis_ids(fixture) == list(FIXTURE_ANALYSES), "the rebuilt Store carries the wrong Analyses")
    check(fixture.validation()["checks"].get("store") == "passed", "the rebuilt Store did not validate")
    check(sha256(fixture.completion("resolve_analysis_metadata")) == resolve_hash,
          "the rerun re-ran the already-complete resolve phase")
    check(not fixture.store_dir.with_name(fixture.store_dir.name + ".partial").exists(),
          "the build left its .partial sibling behind")


