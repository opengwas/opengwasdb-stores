def snakemake(
    fixture: Fixture,
    *,
    until: str | None = None,
    force: str | None = None,
    dry_run: bool = False,
) -> subprocess.CompletedProcess:
    command = [
        str(SNAKEMAKE),
        "--snakefile", str(SNAKEFILE),
        "--configfile", str(fixture.build_yaml),
        "--cores", "1",
        "--printshellcmds",
    ]
    if until:
        command += ["--until", until]
    if force:
        command += ["--forcerun", force]
    if dry_run:
        command += ["--dry-run"]
    return subprocess.run(command, cwd=REPO_ROOT, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)


def planned_rules(result: subprocess.CompletedProcess) -> set[str]:
    """The rules a dry run would execute, from Snakemake's job-stats table."""
    assert_success(result, "dry run")
    return {match.group(1) for match in re.finditer(r"^(\S+)\s+\d+$", result.stdout, re.M)}


