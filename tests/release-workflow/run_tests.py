#!/usr/bin/env python3
"""Production Store Release workflow suite (issue #98; real resolution #99).

    pixi run test                    # or: python3 tests/release-workflow/run_tests.py

The ticket's acceptance criteria are behaviours of the Snakemake DAG, so this
suite drives the real `workflow/Snakefile` against the tiny checked-in
FinnGen-shaped fixture release (`fixtures/r13-fixture/`, regenerated by
`fixtures/generate_r13_fixture.py`) and asserts what the operator sees:

* the one `pixi run release --configfile <build.yaml>` command builds a genuine
  Store end to end, whose `overview.html` is the regenerated one and whose
  `validation.yaml` records the `opengwasdb validate` result;
* issue #99: resolution derives Assigned Ancestry, proportions, and phenotype SD
  into `work/analyses.resolved.tsv` and the built Store, leaves the committed
  `analyses.tsv` byte-identical, names every derived Analysis in
  `sidecars/metadata-resolution.tsv`, records the failed effect-scale check in
  `validation.yaml`, lands the release as `built` rather than `validated`, and
  binds the ancestry reference panel into the completion record;
* a `build.yaml` `effect_scale_validation.block_on_failure` escalates that
  failure to blocking;
* every phase writes a completion record that binds the fixed inputs, the
  `opengwasdb` revision and the effective arguments;
* the validate phase reads the built Store's own `analyses.tsv` back against the
  resolved metadata and manifest it was built from, and probes a binary and a
  quantitative Analysis for finite associations -- the read-back the retired
  `build-store.py` adapters performed by hand (issue #103) -- and a Store that
  dropped a mandated metadata column fails there;
* killing the run before the build, and leaving a partial Store behind, both
  resume rather than treating the partial Store as complete;
* a completed build rerun is a no-op;
* editing `build.yaml`, `analyses.tsv`, a source file, or a declared Reference
  Resource invalidates the affected phases;
* a release whose `analyses.tsv` names its source column `file_name` (rather
  than `source_file`) still resolves and builds;
* the Snakefile itself is wiring only;
* with rho enabled the observed Store gains `data.zarr/rho` and its
  `overview.html` is regenerated *after* it, with the Rho tab present;
* with rho disabled no rho group, record, or tab exists;
* rho on a non-Dense layout is refused at input validation, before any Store
  work;
* with Reference Completion enabled a lineage-linked child Store Release is
  registered and a separate child Store is built, leaving the observed parent
  byte-unchanged;
* the child runs rho, overview regeneration, and validation in the same order
  as the observed release;
* an interrupted completion resumes rather than treating the partial child as
  complete, and a partial child Store is rebuilt rather than trusted;
* issue #104: a catalogue-routed release (`build.command:
  build-hybrid-from-catalogue`) resolves to a routed Analysis Catalogue instead
  of a builder manifest, running `assign_ancestry` then `route_catalogue`, each
  with its own completion record; the derived coverage table drives routing;
  the build keeps exactly the routed-analysis subset and validates; an
  interrupted routing step re-runs routing without re-assigning ancestry; and a
  catalogue-routed command missing a required input is refused before any work.

The fixture is copied into a temporary directory per scenario and its
`artifacts.artifact_root` repointed there, so the suite leaves no Store or work
files in the repository.
"""
