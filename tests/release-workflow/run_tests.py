def rewrite_tsv(path: Path, mutate) -> None:
    fieldnames, rows = _rows(path)
    for row in rows:
        mutate(row)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, delimiter="\t", lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def _rows(path: Path) -> tuple[list[str], list[dict[str, str]]]:
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle, delimiter="\t")
        return list(reader.fieldnames or []), list(reader)


def append_variant(path: Path, row: list[str]) -> None:
    """Append one FinnGen-shaped row, keeping the gzip header timestamp-free."""
    with gzip.open(path, "rt", newline="", encoding="utf-8") as handle:
        existing = list(csv.reader(handle, delimiter="\t"))
    assert existing[0] == ["#chrom", "pos", "ref", "alt", "beta", "sebeta", "af_alt", "rsids"]
    existing.append(row)
    with path.open("wb") as raw:
        with gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as compressed:
            with io.TextIOWrapper(compressed, encoding="utf-8", newline="") as writer:
                csv_writer = csv.writer(writer, delimiter="\t", lineterminator="\n")
                for line in existing:
                    csv_writer.writerow(line)


def assert_success(result: subprocess.CompletedProcess, label: str) -> None:
    if result.returncode != 0:
        raise AssertionError(f"{label} failed (exit {result.returncode}):\n{result.stdout[-4000:]}")


