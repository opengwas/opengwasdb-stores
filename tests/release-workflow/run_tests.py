    check(routed["catalogue-fixture-EUR_1"]["source_assembly"] == "GRCh38",
          "the routed Catalogue dropped the release-level source assembly")

    # The build is the EUR subset: the African Analysis is parked, not dropped.
    check(store_analysis_ids(fixture) == list(CATALOGUE_BUILT_ANALYSES),
          "the built Store carries the wrong Analyses")
