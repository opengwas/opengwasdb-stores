def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


@dataclass(frozen=True)
class Fixture:
    """One temporary copy of the fixture release, wired to a temporary artifact root."""

    release_dir: Path
    work_dir: Path
    store_dir: Path

    @property
    def build_yaml(self) -> Path:
        return self.release_dir / "build.yaml"

    @property
    def analyses(self) -> Path:
        return self.release_dir / "analyses.tsv"

    @property
    def sources(self) -> list[Path]:
        return sorted((self.release_dir / "source").glob("*.gz"))

    def completion(self, phase: str) -> Path:
        return self.work_dir / "completions" / f"{phase}.json"

    def record(self, phase: str) -> dict:
        return json.loads(self.completion(phase).read_text(encoding="utf-8"))

    def validation(self) -> dict:
        return _read_validation(self.release_dir / "validation.yaml")

    def release_status(self) -> str:
        for line in (self.release_dir / "release.yaml").read_text(encoding="utf-8").splitlines():
            if line.startswith("status:"):
                return line.split(":", 1)[1].strip()
        raise AssertionError("release.yaml has no status")

    def sidecar(self, name: str) -> Path:
        return self.release_dir / "sidecars" / name

    def store_analyses(self) -> dict[str, dict[str, str]]:
        return {row["analysis_id"]: row for row in read_tsv(self.store_dir / "analyses.tsv")}

    # Catalogue-routed work files (issue #104); present only for that fixture.
    @property
    def source_manifest(self) -> Path:
        return self.work_dir / "source-manifest.tsv"

    @property
    def analysis_catalogue(self) -> Path:
        return self.work_dir / "analysis-catalogue.tsv"

    @property
    def routed_catalogue(self) -> Path:
        return self.work_dir / "routed-catalogue.tsv"

    @property
    def catalogue_coverage(self) -> Path:
        return self.work_dir / "catalogue-coverage.tsv"


def _read_flat_section(lines: list[str], header: str) -> dict[str, str]:
    """Read one flat `header:` section's `  key: value` children as strings."""
    out: dict[str, str] = {}
    in_section = False
    for line in lines:
        if line == header:
            in_section = True
            continue
        if in_section and line and not line.startswith(" "):
            break
        if in_section and ":" in line:
            key, _, value = line.strip().partition(":")
            out[key.strip()] = value.strip().strip("'\"")
    return out


def _read_validation(path: Path) -> dict:
    """Read the flat `validation.yaml` fields this suite asserts on."""
    lines = path.read_text(encoding="utf-8").splitlines()
    fields: dict[str, str] = {}
    checks: dict[str, str] = {}
    warnings: list[str] = []
    in_checks = False
    in_warnings = False
    for line in lines:
        if line == "checks:":
            in_checks, in_warnings = True, False
            continue
        if line.startswith("warnings:"):
            in_checks, in_warnings = False, True
            continue
        if (in_checks or in_warnings) and line and not line.startswith(" "):
            in_checks = in_warnings = False
        if in_checks and line.startswith("  "):
            key, _, value = line.strip().partition(": ")
            checks[key] = value
        elif in_warnings and line.strip().startswith("- "):
            warnings.append(line.strip()[2:].strip().strip("'\""))
        elif not in_checks and not in_warnings and line and not line.startswith(" ") and ": " in line:
            key, _, value = line.partition(": ")
            fields[key] = value
    fields["checks"] = checks
    fields["warnings"] = warnings
    fields["reports"] = _read_flat_section(lines, "reports:")
    return fields


@dataclass(frozen=True)
class Child:
    """One Reference-Completion child: its Release Bundle and its separate Store."""

    parent: Fixture
    release_id: str
    release_dir: Path
    store_dir: Path
    work_dir: Path

    def completion(self, phase: str) -> Path:
        return self.work_dir / "completions" / f"{phase}.json"

    def record(self, phase: str) -> dict:
        return json.loads(self.completion(phase).read_text(encoding="utf-8"))

    def sidecar(self, name: str) -> Path:
        return self.release_dir / "sidecars" / name

    @property
    def release_yaml(self) -> Path:
        return self.release_dir / "release.yaml"

    @property
    def validation(self) -> dict:
        return _read_validation(self.release_dir / "validation.yaml")

    @property
    def registration(self) -> dict:
        return read_release_yaml(self.release_yaml)


def child_of(fixture: Fixture, release_id: str = CHILD_ID) -> Child:
    """The child paths `workflow/model.py` derives from the observed release."""
    releases = fixture.work_dir.parent.parent  # <artifacts>/finngen-r13/releases
    artifact_dir = releases / release_id
    return Child(
        parent=fixture,
        release_id=release_id,
        release_dir=fixture.release_dir.parent / release_id,
        store_dir=artifact_dir / "store.opengwasdb",
        work_dir=artifact_dir / "work",
    )


def enable_rho(fixture: Fixture, *, arguments: str = "    z-thresh: 100\n    min-nulls: 1\n") -> None:
    """Turn the fixture's rho branch on with explicit opaque arguments."""
    text = fixture.build_yaml.read_text(encoding="utf-8")
    assert "rho:\n  enabled: false\n" in text, "fixture build.yaml has no rho block to enable"
    fixture.build_yaml.write_text(
        text.replace("rho:\n  enabled: false\n", f"rho:\n  enabled: true\n  arguments:\n{arguments}"),
        encoding="utf-8",
    )


def enable_completion(fixture: Fixture, release_id: str = CHILD_ID) -> None:
    """Turn the fixture's Reference-Completion branch on against the fixture panel."""
    text = fixture.build_yaml.read_text(encoding="utf-8")
    assert "reference_completion:\n  enabled: false\n" in text, "fixture build.yaml has no reference_completion block"
    block = (
        "reference_completion:\n  enabled: true\n"
        f"  family_release_id: {release_id}\n"
        "  command: complete-dense\n"
        "  arguments:\n"
        f"    ld-panel: {FIXTURE_PANEL}\n"
        "    ancestry: EUR\n"
        f"    release-id: {release_id}\n"
        "    min-cor: 0.0\n"
    )
    fixture.build_yaml.write_text(
        text.replace("reference_completion:\n  enabled: false\n", block), encoding="utf-8"
    )


def rho_group_attrs(store_dir: Path) -> dict | None:
    """The `data.zarr/rho` group's provenance attributes, or None if absent."""
    import zarr

    if not (store_dir / "data.zarr").is_dir():
        return None
    root = zarr.open_group(str(store_dir / "data.zarr"), mode="r")
    if "rho" not in root:
        return None
    return dict(root["rho"].attrs)


def store_variant_count(store_dir: Path) -> int:
    from opengwasdb.variants import VariantAxis

    axis = VariantAxis(store_dir)
    try:
        return int(axis.n_variants)
    finally:
        axis.close()


def store_fingerprint(store_dir: Path) -> str:
    """Content hash of every file in a Store, so byte-stability is checkable."""
    digest = hashlib.sha256()
    for path in sorted(item for item in store_dir.rglob("*") if item.is_file()):
        digest.update(str(path.relative_to(store_dir)).encode())
        digest.update(path.read_bytes())
    return digest.hexdigest()


def prepare(temp_root: Path, name: str) -> Fixture:
    """Copy the fixture release and point its artifact root at the temp directory."""
    scenario = temp_root / name
